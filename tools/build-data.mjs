import {readFile,writeFile} from 'node:fs/promises';
const read=async f=>JSON.parse(await readFile(new URL('../'+f,import.meta.url),'utf8'));
const tasks=await read('data/tasks.json'), roster=await read('data/roster.json'), events=await read('data/events.json'), catalog=await read('assets/catalog.json');
await writeFile(new URL('../lib/config.js',import.meta.url),'// Generated by tools/build-data.mjs. Edit data/*.json instead.\n'+
 'export const TASKS = '+JSON.stringify(tasks.tasks)+';\n'+
 'export const ROSTER = '+JSON.stringify(roster)+';\n'+
 'export const EVENTS = '+JSON.stringify(events.events)+';\n'+
 'export const CATALOG = '+JSON.stringify(catalog)+';\n');
